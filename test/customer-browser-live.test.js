import test from 'node:test';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { chromium } from '@playwright/test';
import sharp from 'sharp';

const base = process.env.CLASSIC_MART_LIVE_BASE_URL;
test('live approved customer UI supports signup, address submission, mobile navigation and logout in Chromium', {skip:!base}, async () => {
  assert.equal(new URL(base).hostname,'127.0.0.1');
  const browser = await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || undefined,args:['--no-sandbox']});
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1000}});
    const errors = [];
    page.on('pageerror',error=>errors.push(error.message));
    const suffix = crypto.randomBytes(6).toString('hex');
    await page.goto(base+'/signup');
    for (const [name,value] of Object.entries({name:'Browser Customer',email:`browser-${suffix}@example.com`,phone:'+2567'+crypto.randomInt(10000000,99999999),password:`Browser-${suffix}A1!`,confirmPassword:`Browser-${suffix}A1!`})) await page.locator(`[name="${name}"]`).fill(value);
    await page.locator('[name="acceptTerms"]').check();
    await page.locator('button[type="submit"]').click();
    await page.waitForURL('**/dashboard');
    assert.equal(await page.locator('#roleSwitcher').count(),0);
    assert.equal(await page.locator('#workspaceLabel,.workspace-switcher').count(),0);
    assert.ok(await page.locator('#searchForm').isVisible());
    // Use the actual popup controls: stopping propagation inside this menu
    // previously prevented all three delegated actions from reaching the router.
    await page.locator('#profileButton').click();
    await page.locator('#profileMenu [data-profile-tab="security"]').click();
    await page.waitForURL(base+'/account/security');
    assert.equal(await page.locator('body').getAttribute('data-dashboard-workspace'),'customer');
    assert.equal(await page.getByRole('heading',{name:'Password & security',exact:true}).count(),1);
    await page.locator('#profileButton').click();
    await page.locator('#profileMenu [data-page-target="profile"]:not([data-profile-tab])').click();
    await page.waitForURL(base+'/profile');
    assert.equal(await page.getByRole('heading',{name:'Profile Settings',exact:true}).count(),1);
    await page.locator('.side-link[data-page-target="addresses"]').click();
    await page.waitForURL('**/addresses*');
    for (const [name,value] of Object.entries({fullName:'Browser Customer',phone:'+256700000003',address:'Browser verified address',city:'Kampala',region:'Central Region',postalCode:'256'})) await page.locator(`#addressForm [name="${name}"]`).fill(value);
    await page.locator('#addressForm [name="label"]').selectOption('Home');
    await page.locator('#addressForm button[type="submit"]').click();
    await page.waitForURL('**/addresses*');
    await page.locator('[data-address-id]').first().waitFor();
    assert.match(await page.locator('[data-address-id]').first().innerText(),/Browser verified address/);
    await page.reload();
    assert.match(await page.locator('[data-address-id]').first().innerText(),/Browser verified address/);
    assert.equal(await page.locator('[data-address-id]').first().getAttribute('data-address-region'),'Central Region');
    assert.equal(await page.locator('[data-address-id]').first().getAttribute('data-address-postal-code'),'256');
    await page.locator('[data-address-edit]').first().click();
    const addressDialog=page.locator('.record-modal[open]');
    await addressDialog.waitFor({state:'visible'});
    const addressEditForm=addressDialog.locator('form[method="post"]');
    assert.equal(await addressEditForm.locator('[name="region"]').inputValue(),'Central Region');
    assert.equal(await addressEditForm.locator('[name="postalCode"]').inputValue(),'256');
    await addressEditForm.locator('[name="address"]').fill('Updated browser delivery address');
    await addressEditForm.locator('[name="note"]').fill('Browser delivery instruction');
    await addressEditForm.locator('button[type="submit"]').click();
    await addressDialog.getByText('Address updated.',{exact:true}).waitFor();
    await Promise.all([page.waitForNavigation(),addressDialog.getByRole('button',{name:'Close record',exact:true}).click()]);
    await page.waitForURL('**/addresses');
    assert.match(await page.locator('[data-address-id]').first().innerText(),/Updated browser delivery address/);
    assert.equal(await page.locator('[data-address-id]').first().getAttribute('data-address-region'),'Central Region');
    assert.equal(await page.locator('[data-address-id]').first().getAttribute('data-address-postal-code'),'256');
    assert.equal(await page.locator('[data-address-id]').first().getAttribute('data-address-note'),'Browser delivery instruction');
    await page.goto(base+'/profile');
    const avatar=await sharp({create:{width:400,height:400,channels:3,background:'#ed6c16'}}).png().toBuffer();
    await page.locator('#customerAvatarInput').setInputFiles({name:'browser-avatar.png',mimeType:'image/png',buffer:avatar});
    await page.waitForFunction(()=>document.querySelector('#customerAvatarPreview')?.src.startsWith('blob:'));
    await Promise.all([page.waitForNavigation(),page.locator('#profilePhotoForm button[type="submit"]').click()]);
    assert.match(await page.locator('#customerAvatarPreview').getAttribute('src'),/^\/account\/avatar\?v=/);
    await page.waitForFunction(()=>document.querySelector('#customerAvatarPreview')?.naturalWidth===320);
    const storedAvatarUrl=await page.locator('#customerAvatarPreview').getAttribute('src');
    const removeAvatar=page.locator('form[action="/account/avatar/delete"] button');
    await removeAvatar.click();
    const deleteConfirmation=page.getByRole('dialog',{name:'Confirm deletion',exact:true});
    await deleteConfirmation.waitFor({state:'visible'});
    await deleteConfirmation.getByRole('button',{name:'Cancel',exact:true}).click();
    assert.equal(await page.locator('#customerAvatarPreview').getAttribute('src'),storedAvatarUrl);
    assert.equal(await page.locator('#customerAvatarPreview').evaluate(image=>image.naturalWidth),320);
    assert.equal((await page.request.get(new URL(storedAvatarUrl,base).href)).status(),200);
    await removeAvatar.click();
    await deleteConfirmation.waitFor({state:'visible'});
    await Promise.all([page.waitForNavigation(),deleteConfirmation.getByRole('button',{name:'Continue',exact:true}).click()]);
    assert.match(await page.locator('#customerAvatarPreview').getAttribute('src'),/^\/approved-dashboard\/assets\/avatar\.svg(?:\?v=[a-f0-9]{16})?$/);
    await page.setViewportSize({width:390,height:844});
    await page.locator('#mobileMenuBtn').click();
    assert.equal(await page.locator('#sidebarOverlay').evaluate(el=>el.classList.contains('show')),true);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#sidebar').evaluate(el=>el.classList.contains('open')),false);
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+2));
    await page.locator('#profileButton').click();
    await page.locator('#profileMenu [data-action="logout"]').click();
    await page.waitForURL('**/login');
    await page.goto(base+'/dashboard');
    assert.match(page.url(),/\/login/);
    assert.deepEqual(errors,[]);
  } finally { await browser.close(); }
});
